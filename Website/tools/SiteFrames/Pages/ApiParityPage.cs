using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json.Nodes;

namespace SiteFrames.Pages {
    /// <summary>Publishes the member decisions from the same contract consumed by the parity gate and demo notes.</summary>
    internal static class ApiParityPage {
        public static void Render(Site site) {
            JsonObject map = JsonNode.Parse(File.ReadAllText(Path.Combine(site.Repository, "Tests", "Api", "round2-parity.json")))!.AsObject();
            JsonArray commands = map["Commands"]!.AsArray();
            var body = new StringBuilder();
            body.AppendLine("<!-- Generated by SiteFrames render from Tests/Api/round2-parity.json. -->");
            body.AppendLine("# PowerShell and C# API parity\n");
            body.AppendLine("I use the same domain names for cmdlet parameters, C# configuration and fluent calls. PowerShell keeps numeric duration parameters with units and default-off switches; C# keeps TimeSpan values and Boolean properties.\n");
            body.AppendLine("The contract covers **" + commands.Count + " commands**, **" + commands.Sum(command => command!["Bindings"]!.AsArray().Count) + " parameters** and **" + map["ConfigurableTypes"]!.AsArray().Count + " reachable public types**. The metadata gate checks names, types, sets, positions, defaults, nullability and member paths. Rendering and triplet tests check behavior.\n");
            body.AppendLine("Table and List remain named shortcuts to Show-Console’s shared view implementation. Read-* returns answers; New-ConsoleForm/Menu defines a question workflow; Show-ConsoleApp runs a persistent reactive application.\n");
            body.AppendLine("Typed Options on export, form, menu and replay operations expose the corresponding C# configuration. I can pass a PowerShell hashtable, for example `Export-ConsoleFrame -Format Html -Options @{ Width = 100; Padding = 8 }`. Options and individual settings are mutually exclusive; the supplied request is not modified.\n");
            body.AppendLine("## Parameter-set mappings\n");
            body.AppendLine("A structural parameter set can select a different request model. The metadata gate checks these mappings separately and includes both update requests in its public-member coverage.\n");
            body.AppendLine("| Command and parameter | Set | C# member | Conversion |\n| --- | --- | --- | --- |");
            foreach (JsonNode? commandNode in commands) {
                JsonObject command = commandNode!.AsObject();
                foreach (JsonNode? node in command["SetBindings"]?.AsArray() ?? new JsonArray()) {
                    JsonObject row = node!.AsObject();
                    body.AppendLine("| `" + Cell(command["Command"]!.GetValue<string>() + " -" + row["Parameter"]!.GetValue<string>()) + "` | "
                        + Cell(row["ParameterSet"]!.GetValue<string>()) + " | `" + Cell(row["CSharpType"]!.GetValue<string>() + "." + row["Member"]!.GetValue<string>())
                        + "` | " + Cell(row["Reason"]?.GetValue<string>() ?? row["Conversion"]!.GetValue<string>()) + " |");
                }
            }
            body.AppendLine("## Individual member decisions\n");
            body.AppendLine("Native host hooks, runtime models and equivalent representations are listed individually. These decisions do not exempt a namespace or hide newly added options.\n");
            body.AppendLine("| C# member | Disposition and reason | PowerShell route or alternative |\n| --- | --- | --- |");
            foreach (JsonNode? node in map["CSharpOnly"]!.AsArray()) {
                JsonObject row = node!.AsObject();
                body.AppendLine("| `" + Cell(row["CSharpType"]!.GetValue<string>() + "." + row["Member"]!.GetValue<string>()) + "` | "
                    + Cell(row["Disposition"]!.GetValue<string>() + ": " + row["Reason"]!.GetValue<string>()) + " | " + Cell(row["Alternative"]!.GetValue<string>()) + " |");
            }
            body.AppendLine("\n## .NET host integrations\n");
            body.AppendLine("The PowerShell formatting, help and progress examples run inside a compiled PSCmdlet on its owning pipeline thread. The generic-host and ILogger examples configure .NET lifetimes; their PowerShell tab launches the same project. These options remain explicit C# integration settings.\n");
            body.AppendLine("| Package and C# member | PowerShell route and reason |\n| --- | --- |");
            foreach (JsonNode? node in map["IntegrationOptions"]!.AsArray()) {
                JsonObject integration = node!.AsObject();
                foreach (JsonNode? member in integration["Members"]!.AsArray()) {
                    body.AppendLine("| `" + Cell(integration["CSharpType"]!.GetValue<string>() + "." + member!.GetValue<string>()) + "` (" + Cell(integration["Package"]!.GetValue<string>()) + ") | `dotnet run`: " + Cell(integration["Reason"]!.GetValue<string>()) + " |");
                }
            }
            string markdown = body.ToString();
            site.Write(Path.Combine(site.Repository, "Docs", "Api-Parity.md"), markdown);
            site.Write(Path.Combine(site.Website, "content", "docs", "api-parity.md"),
                "---\ntitle: PowerShell and C# API parity\ndescription: \"The shared parameter and fluent vocabulary, including every C# host-only member decision.\"\nslug: api-parity\norder: 16\ngroup: hosts\ncard: three-fluent\n---\n\n" + markdown);
        }

        private static string Cell(string value) => value.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
    }
}
