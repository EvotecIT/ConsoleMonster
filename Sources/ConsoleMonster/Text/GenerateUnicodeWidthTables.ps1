# Regenerates the compact Unicode 17.0 terminal width and grapheme tables.
# Run explicitly when updating Unicode data; this is not a build-time dependency.
$ErrorActionPreference = 'Stop'
$unicodeBase = 'https://www.unicode.org/Public/17.0.0/ucd/'
function Read-PropertyData([string] $RelativePath) {
    $content = (Invoke-WebRequest -Uri ($unicodeBase + $RelativePath)).Content
    if ($content -is [byte[]]) { $content = [Text.Encoding]::UTF8.GetString($content) }
    foreach ($line in ($content -split '\r?\n')) {
        $body = ($line -split '#', 2)[0].Trim()
        if (!$body) { continue }
        $fields = $body -split '\s*;\s*'
        $bounds = $fields[0] -split '\.\.'
        [pscustomobject]@{
            Start = [Convert]::ToInt32($bounds[0], 16)
            End = [Convert]::ToInt32($bounds[-1], 16)
            Property = $fields[1]
            Value = if ($fields.Length -gt 2) { $fields[2] } else { '' }
        }
    }
}
$eastAsian = @(Read-PropertyData 'EastAsianWidth.txt')
$categories = @(Read-PropertyData 'extracted/DerivedGeneralCategory.txt')
$graphemes = @(Read-PropertyData 'auxiliary/GraphemeBreakProperty.txt')
$emoji = @(Read-PropertyData 'emoji/emoji-data.txt')
$core = @(Read-PropertyData 'DerivedCoreProperties.txt')
$tables = [ordered]@{
    Wide = @($eastAsian | Where-Object Property -In 'W','F')
    ZeroWidth = @($categories | Where-Object Property -In 'Mn','Me','Cf','Cc')
    Extend = @($graphemes | Where-Object Property -EQ 'Extend')
    SpacingMark = @($graphemes | Where-Object Property -EQ 'SpacingMark')
    Prepend = @($graphemes | Where-Object Property -EQ 'Prepend')
    Control = @($graphemes | Where-Object Property -In 'Control','CR','LF')
    EmojiPresentation = @($emoji | Where-Object Property -EQ 'Emoji_Presentation')
    Emoji = @($emoji | Where-Object Property -EQ 'Emoji')
    ExtendedPictographic = @($emoji | Where-Object Property -EQ 'Extended_Pictographic')
    IndicConsonant = @($core | Where-Object { $_.Property -eq 'InCB' -and $_.Value -eq 'Consonant' })
    IndicLinker = @($core | Where-Object { $_.Property -eq 'InCB' -and $_.Value -eq 'Linker' })
    IndicExtend = @($core | Where-Object { $_.Property -eq 'InCB' -and $_.Value -eq 'Extend' })
}
$license = (Invoke-WebRequest -Uri 'https://www.unicode.org/license.txt').Content
if ($license -is [byte[]]) { $license = [Text.Encoding]::UTF8.GetString($license) }
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by GenerateUnicodeWidthTables.ps1 from Unicode 17.0.0 UCD.')
[void]$output.AppendLine('// Sources: https://www.unicode.org/Public/17.0.0/ucd/')
[void]$output.AppendLine('/*')
[void]$output.AppendLine($license.Trim())
[void]$output.AppendLine('*/')
[void]$output.AppendLine('namespace ConsoleMonster.Text {')
[void]$output.AppendLine('    internal static class UnicodeWidthTables {')
foreach ($entry in $tables.GetEnumerator()) {
    $merged = [Collections.Generic.List[object]]::new()
    foreach ($range in ($entry.Value | Sort-Object Start, End)) {
        if ($merged.Count -gt 0 -and $range.Start -le ($merged[-1].End + 1)) {
            $merged[-1].End = [Math]::Max($merged[-1].End, $range.End)
        } else {
            $merged.Add([pscustomobject]@{ Start = $range.Start; End = $range.End })
        }
    }
    [void]$output.AppendLine(('        internal static readonly int[] {0} = {{' -f $entry.Key))
    $pairs = @($merged | ForEach-Object { '0x{0:X}, 0x{1:X}' -f $_.Start, $_.End })
    for ($i = 0; $i -lt $pairs.Count; $i += 4) {
        $last = [Math]::Min($i + 3, $pairs.Count - 1)
        [void]$output.AppendLine(('            ' + ($pairs[$i..$last] -join ', ') + ','))
    }
    [void]$output.AppendLine('        };')
}
[void]$output.AppendLine('')
[void]$output.AppendLine('        internal static bool Contains(int[] ranges, int value) {')
[void]$output.AppendLine('            int low = 0;')
[void]$output.AppendLine('            int high = (ranges.Length / 2) - 1;')
[void]$output.AppendLine('            while (low <= high) {')
[void]$output.AppendLine('                int middle = low + ((high - low) / 2);')
[void]$output.AppendLine('                if (value < ranges[middle * 2]) {')
[void]$output.AppendLine('                    high = middle - 1;')
[void]$output.AppendLine('                } else if (value > ranges[(middle * 2) + 1]) {')
[void]$output.AppendLine('                    low = middle + 1;')
[void]$output.AppendLine('                } else {')
[void]$output.AppendLine('                    return true;')
[void]$output.AppendLine('                }')
[void]$output.AppendLine('            }')
[void]$output.AppendLine('            return false;')
[void]$output.AppendLine('        }')
[void]$output.AppendLine('    }')
[void]$output.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'UnicodeWidthTables.cs'), $output.ToString(), [Text.UTF8Encoding]::new($false))
