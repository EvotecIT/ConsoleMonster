        internal static bool Contains(int scalar) {
            int low = 0;
            int high = Ranges.Length / 2 - 1;
            while (low <= high) {
                int middle = low + (high - low) / 2;
                if (scalar < Ranges[middle * 2]) high = middle - 1;
                else if (scalar > Ranges[middle * 2 + 1]) low = middle + 1;
                else return true;
            }
            return false;
        }
