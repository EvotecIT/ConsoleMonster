using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using ConsoleMonster.Layout;

namespace ConsoleMonster.PowerShell {
    /// <summary>
    /// Generates ConsoleMonster.format.ps1xml from the widget types themselves: every public, non-abstract
    /// <see cref="IWidget"/> in ConsoleMonster, ConsoleMonster.Graphics and ConsoleMonster.PowerShell, and <see cref="ConsoleRendering"/> (live or deserialized), gets the
    /// view that draws it (<see cref="WidgetFormatter"/>). Nothing is listed by hand: Module/Build/Update-ConsoleFormatData.ps1
    /// writes the file and a test fails when it is out of date.
    /// </summary>
    internal static class WidgetFormatData {
        /// <summary>The name of the view.</summary>
        public const string ViewName = "ConsoleMonster.Widget";

        /// <summary>A <see cref="ConsoleRendering"/> that crossed a serialization boundary (Export-Clixml, a child pwsh, remoting): drawn from the text it carries.</summary>
        public const string DeserializedRendering = "Deserialized.ConsoleMonster.PowerShell.ConsoleRendering";

        /// <summary>The type names the view is selected by, sorted.</summary>
        /// <returns>The type names.</returns>
        public static IReadOnlyList<string> TypeNames() {
            SortedSet<string> names = new SortedSet<string>(StringComparer.Ordinal) { typeof(ConsoleRendering).FullName!, DeserializedRendering };
            foreach (Type type in typeof(IWidget).Assembly.GetExportedTypes().Concat(typeof(WidgetFormatData).Assembly.GetExportedTypes())
                .Concat(typeof(Graphics.ConsoleImage).Assembly.GetExportedTypes())) {
                if (type.IsClass && !type.IsAbstract && !type.IsGenericTypeDefinition && typeof(IWidget).IsAssignableFrom(type) && type.FullName != null) {
                    names.Add(type.FullName);
                }
            }
            return names.ToList();
        }

        /// <summary>The type name Get-ConsoleDemo gives its records, so the gallery lists as a table.</summary>
        public const string DemoTypeName = "ConsoleMonster.ConsoleDemo";

        /// <summary>The name of the out-of-band view for renderings.</summary>
        public const string RenderingViewName = "ConsoleMonster.Rendering";

        /// <summary>The format file's content.</summary>
        /// <returns>The XML text.</returns>
        public static string Generate() {
            StringBuilder xml = new StringBuilder();
            xml.Append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
            xml.Append("<!-- Generated by ((Get-Command Show-Console).ImplementingType.Assembly.GetType('ConsoleMonster.PowerShell.WidgetFormatData'))::Generate(); do not edit. Regenerate with Module/Build/Update-ConsoleFormatData.ps1. -->\n");
            xml.Append("<Configuration>\n  <ViewDefinitions>\n");
            List<string> renderings = new List<string>();
            List<string> widgets = new List<string>();
            foreach (string name in TypeNames()) {
                (name == typeof(ConsoleRendering).FullName || name == DeserializedRendering ? renderings : widgets).Add(name);
            }
            // Renderings are out of band: drawn on their own also in the middle of another table (an error view between
            // table rows), as PowerShell draws error records. Widgets are not, so Format-List * still lists their properties.
            AppendView(xml, RenderingViewName, renderings, true);
            AppendView(xml, ViewName, widgets, false);
            AppendDemoView(xml);
            xml.Append("  </ViewDefinitions>\n</Configuration>\n");
            return xml.ToString();
        }

        private static void AppendView(StringBuilder xml, string name, List<string> types, bool outOfBand) {
            xml.Append("    <View>\n      <Name>").Append(name).Append("</Name>\n");
            if (outOfBand) {
                xml.Append("      <OutOfBand />\n");
            }
            xml.Append("      <ViewSelectedBy>\n");
            foreach (string type in types) {
                xml.Append("        <TypeName>").Append(type).Append("</TypeName>\n");
            }
            xml.Append("      </ViewSelectedBy>\n");
            xml.Append("      <CustomControl>\n        <CustomEntries>\n          <CustomEntry>\n            <CustomItem>\n              <ExpressionBinding>\n");
            xml.Append("                <ScriptBlock>((Get-Command Show-Console).ImplementingType.Assembly.GetType('ConsoleMonster.PowerShell.WidgetFormatter'))::Format($_, $Host, $(if ($style = Get-Variable -Name PSStyle -ValueOnly -ErrorAction Ignore) { [string] $style.OutputRendering } else { '' }))</ScriptBlock>\n");
            xml.Append("              </ExpressionBinding>\n            </CustomItem>\n          </CustomEntry>\n        </CustomEntries>\n      </CustomControl>\n");
            xml.Append("    </View>\n");
        }

        // Get-ConsoleDemo: what each demo is called and how to run it, not the whole metadata record.
        private static void AppendDemoView(StringBuilder xml) {
            string[][] columns = { new[] { "Slug", "slug" }, new[] { "Category", "category" }, new[] { "Mode", "mode" }, new[] { "Title", "title" } };
            xml.Append("    <View>\n      <Name>").Append(DemoTypeName).Append("</Name>\n");
            xml.Append("      <ViewSelectedBy>\n        <TypeName>").Append(DemoTypeName).Append("</TypeName>\n      </ViewSelectedBy>\n");
            xml.Append("      <TableControl>\n        <TableHeaders>\n");
            foreach (string[] column in columns) {
                xml.Append("          <TableColumnHeader>\n            <Label>").Append(column[0]).Append("</Label>\n          </TableColumnHeader>\n");
            }
            xml.Append("        </TableHeaders>\n        <TableRowEntries>\n          <TableRowEntry>\n            <TableColumnItems>\n");
            foreach (string[] column in columns) {
                xml.Append("              <TableColumnItem>\n                <PropertyName>").Append(column[1]).Append("</PropertyName>\n              </TableColumnItem>\n");
            }
            xml.Append("            </TableColumnItems>\n          </TableRowEntry>\n        </TableRowEntries>\n      </TableControl>\n");
            xml.Append("    </View>\n");
        }
    }
}
